// Bundles the Excel Office.js API layer from hewliyang/office-agents (MIT)
// into a browser ES module the task pane imports directly.
//
// Usage: node scripts/vendor-office-agents.mjs [path-to-office-agents-checkout]

import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { patchOfficeAgentsExcelApi } from "./office-agents-patches.mjs";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = resolve(process.argv[2] ?? join(projectRoot, "..", "_sdks", "office-agents"));
const entry = join(sourceRoot, "packages", "excel", "src", "lib", "excel", "api.ts");
const outfile = join(projectRoot, "taskpane", "shared", "vendor", "office-agents-excel-api.js");
const EXPECTED_COMMIT = "95fb654491a9d394dc85ea2b8c93dee2ca4546b9";

if (!existsSync(entry)) {
  console.error(`office-agents Excel API not found at ${entry}`);
  process.exit(1);
}

const commit = execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
if (commit !== EXPECTED_COMMIT) {
  throw new Error(
    `office-agents is at ${commit}; expected ${EXPECTED_COMMIT}. Review upstream changes and update the patches before changing the pin.`,
  );
}
const sourceStatus = execFileSync("git", ["-C", sourceRoot, "status", "--porcelain"], {
  encoding: "utf8",
}).trim();
if (sourceStatus) {
  throw new Error(
    "office-agents checkout has uncommitted changes; refusing a non-reproducible build",
  );
}

const patchedEntry = patchOfficeAgentsExcelApi(await readFile(entry, "utf8"));

await build({
  absWorkingDir: sourceRoot,
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  target: "es2022",
  legalComments: "inline",
  plugins: [
    {
      name: "excel-assistant-office-agents-patches",
      setup(builder) {
        builder.onLoad({ filter: /api\.ts$/ }, async (args) => {
          if (resolve(args.path) !== resolve(entry)) return null;
          return { contents: patchedEntry, loader: "ts", resolveDir: dirname(entry) };
        });
      },
    },
  ],
  banner: {
    js: [
      "// Generated by scripts/vendor-office-agents.mjs — do not edit by hand.",
      `// Source: https://github.com/hewliyang/office-agents @ ${commit}`,
      "// License: MIT (c) hewliyang",
    ].join("\n"),
  },
});

console.log(`Wrote ${outfile} from office-agents@${commit.slice(0, 7)}`);
