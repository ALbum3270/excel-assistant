// Bundles the workbook-context readers from tmustier/pi-for-excel (MIT) —
// workbook overview, selection context and change tracker — into a browser
// ES module the task pane imports directly.
//
// Usage: node scripts/vendor-pi-context.mjs [path-to-pi-for-excel-checkout]

import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { copyFile, readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { patchChangeTracker, patchSelectionContext, patchWorkbookOverview } from "./pi-context-patches.mjs";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = resolve(process.argv[2] ?? join(projectRoot, "..", "_sdks", "pi-for-excel"));
const selectionFile = join(sourceRoot, "src", "context", "selection.ts");
const changeTrackerFile = join(sourceRoot, "src", "context", "change-tracker.ts");
const overviewFile = join(sourceRoot, "src", "tools", "get-workbook-overview.ts");
const outfile = join(projectRoot, "taskpane", "shared", "vendor", "pi-context.js");
const licenseOutfile = join(projectRoot, "taskpane", "shared", "vendor", "pi-context.LICENSE");
const EXPECTED_COMMIT = "fd6c9e3c3b206d6e2e39a2957c70714fdc879727";

if (!existsSync(selectionFile)) {
  console.error(`pi-for-excel sources not found at ${sourceRoot}`);
  process.exit(1);
}

const commit = execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
if (commit !== EXPECTED_COMMIT) {
  throw new Error(
    `pi-for-excel is at ${commit}; expected ${EXPECTED_COMMIT}. Review upstream changes and update the patches before changing the pin.`,
  );
}
const sourceStatus = execFileSync("git", ["-C", sourceRoot, "status", "--porcelain"], {
  encoding: "utf8",
}).trim();
if (sourceStatus) {
  throw new Error("pi-for-excel checkout has uncommitted changes; refusing a non-reproducible build");
}

const patchedSelection = patchSelectionContext(await readFile(selectionFile, "utf8"));
const patchedChangeTracker = patchChangeTracker(await readFile(changeTrackerFile, "utf8"));
const patchedOverview = patchWorkbookOverview(await readFile(overviewFile, "utf8"));

await build({
  absWorkingDir: sourceRoot,
  stdin: {
    contents: [
      'export { buildOverview } from "./src/tools/get-workbook-overview.ts";',
      'export { readSelectionContext } from "./src/context/selection.ts";',
      'export { ChangeTracker } from "./src/context/change-tracker.ts";',
    ].join("\n"),
    resolveDir: sourceRoot,
    loader: "ts",
    sourcefile: "pi-context-entry.ts",
  },
  outfile,
  bundle: true,
  format: "esm",
  target: "es2022",
  legalComments: "inline",
  plugins: [
    {
      name: "excel-assistant-pi-context",
      setup(builder) {
        builder.onLoad({ filter: /selection\.ts$/ }, (args) => {
          if (resolve(args.path) !== resolve(selectionFile)) return null;
          return { contents: patchedSelection, loader: "ts", resolveDir: dirname(selectionFile) };
        });
        builder.onLoad({ filter: /change-tracker\.ts$/ }, (args) => {
          if (resolve(args.path) !== resolve(changeTrackerFile)) return null;
          return { contents: patchedChangeTracker, loader: "ts", resolveDir: dirname(changeTrackerFile) };
        });
        builder.onLoad({ filter: /get-workbook-overview\.ts$/ }, (args) => {
          if (resolve(args.path) !== resolve(overviewFile)) return null;
          return { contents: patchedOverview, loader: "ts", resolveDir: dirname(overviewFile) };
        });
        // get-workbook-overview.ts builds its tool schema with typebox at load
        // time; buildOverview never reads it, so a no-op builder is enough.
        builder.onResolve({ filter: /^(typebox|@sinclair\/typebox)$/ }, () => ({
          path: "typebox-stub",
          namespace: "excel-assistant-stub",
        }));
        builder.onLoad({ filter: /.*/, namespace: "excel-assistant-stub" }, () => ({
          contents: "export const Type = new Proxy({}, { get: () => () => ({}) });",
          loader: "js",
        }));
      },
    },
  ],
  banner: {
    js: [
      "// Generated by scripts/vendor-pi-context.mjs — do not edit by hand.",
      `// Source: https://github.com/tmustier/pi-for-excel @ ${commit}`,
      "// License: MIT (c) 2026 Thomas Mustier",
    ].join("\n"),
  },
});

// Recovery checkpoints (Pi's workbook_history backend). Storage, workbook
// identity and the document token are injected by taskpane/shared/recovery.js,
// so Pi's host and storage singletons are replaced by stubs that never run.
// typebox is real here: the log validates persisted snapshots with it.
const recoveryOutfile = join(projectRoot, "taskpane", "shared", "vendor", "pi-recovery.js");
const typeboxLicenseOutfile = join(projectRoot, "taskpane", "shared", "vendor", "typebox.LICENSE");
const recoveryStubs = {
  "host-current":
    "export function getCurrentSpreadsheetHost() { throw new Error('Pi host is not bundled; inject getWorkbookContext and getDocumentInstance'); }",
  "app-storage": "export function getAppStorage() { return { settings: null }; }",
  // pi-ai's StringEnum: a string schema restricted to the listed values.
  "pi-ai":
    "import { Type } from 'typebox'; export function StringEnum(values, options) { return Type.Unsafe({ type: 'string', enum: [...values], ...(options ?? {}) }); }",
};

await build({
  absWorkingDir: sourceRoot,
  stdin: {
    contents: [
      'export { WorkbookRecoveryLog, MAX_RECOVERY_CELLS } from "./src/workbook/recovery-log.ts";',
      'export { captureFormatCellsState } from "./src/workbook/recovery-states.ts";',
    ].join("\n"),
    resolveDir: sourceRoot,
    loader: "ts",
    sourcefile: "pi-recovery-entry.ts",
  },
  outfile: recoveryOutfile,
  bundle: true,
  format: "esm",
  target: "es2022",
  legalComments: "inline",
  nodePaths: [join(projectRoot, "node_modules")],
  plugins: [
    {
      name: "excel-assistant-pi-recovery",
      setup(builder) {
        builder.onResolve({ filter: /\/host\/current\.js$/ }, () => ({ path: "host-current", namespace: "pi-stub" }));
        builder.onResolve({ filter: /\/storage\/local\/app-storage\.js$/ }, () => ({ path: "app-storage", namespace: "pi-stub" }));
        builder.onResolve({ filter: /^@earendil-works\/pi-ai$/ }, () => ({ path: "pi-ai", namespace: "pi-stub" }));
        builder.onLoad({ filter: /.*/, namespace: "pi-stub" }, (args) => ({
          contents: recoveryStubs[args.path],
          loader: "js",
          resolveDir: projectRoot,
        }));
      },
    },
  ],
  banner: {
    js: [
      "// Generated by scripts/vendor-pi-context.mjs — do not edit by hand.",
      `// Source: https://github.com/tmustier/pi-for-excel @ ${commit}`,
      "// License: MIT (c) 2026 Thomas Mustier; bundles typebox (MIT (c) Haydn Paterson)",
    ].join("\n"),
  },
});

await copyFile(join(sourceRoot, "LICENSE"), licenseOutfile);
await copyFile(join(projectRoot, "node_modules", "typebox", "license"), typeboxLicenseOutfile);

console.log(`Wrote ${outfile} and ${recoveryOutfile} from pi-for-excel@${commit.slice(0, 7)}`);
